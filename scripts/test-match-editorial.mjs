import assert from "node:assert/strict";
import fs from "node:fs";
import { readMatchEditorial, matchEditorialHtml } from "./lib/matchEditorial.mjs";
const root = process.cwd();
const slug = "galatasaray-amed-sportif-faaliyetler-7-kasim-2026";
const entry = { slug, providerIds: { apiFootball: "1584461" } };
const data = readMatchEditorial(root, entry);
assert.ok(data);
assert.throws(() => readMatchEditorial(root, { ...entry, providerIds: { apiFootball: "wrong" } }), /identity mismatch/);
assert.equal(readMatchEditorial(root, { slug: "does-not-exist" }), null);
const html = matchEditorialHtml(data);
assert.match(html, /5 galibiyet, 13 gol atıp 3 gol yeme/);
for (const term of ["19:00", "RAMS Park", "11. hafta", "Halil Umut Meler", "artroskopik", "Osimhen 9", "Orban 9", "40 maç", "5-1", "3 maç men"]) assert.ok(html.includes(term), term);
for (const link of html.matchAll(/<a href="https?:[^>]+>/g)) assert.match(link[0], /rel="nofollow noopener noreferrer"/);
const page = fs.readFileSync(`mac/${slug}.html`, "utf8");
assert.match(page, new RegExp(`<link rel="canonical" href="https://www.futbolradar.com/mac/${slug}"`));
assert.match(page, /"@type":"SportsEvent"/);
assert.match(page, /"@type":"BreadcrumbList"/);
assert.ok(page.includes(html));
assert.ok(!page.includes('data-msp-lineups'), "do not republish the stale probable XI containing Osimhen");
assert.ok(!page.includes("12 puan / 5 maç"), "do not repeat stale form alongside sourced last five");
assert.match(page, /pwa\.js/);
for (const file of ["index.html", "takimlar/galatasaray.html", "takimlar/amed.html", "sitemap.xml", "sitemaps/sitemap-matches.xml"]) assert.ok(fs.readFileSync(file, "utf8").includes(`mac/${slug}`), file);
assert.ok(!fs.existsSync("galatasaray-amedspor.html"), "keep one permanent match URL");
console.log("match-editorial: sources, identity, requested facts, form totals, SEO, discovery, PWA passed");
