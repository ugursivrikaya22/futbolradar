import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { renderPlayer360 } from "./lib/player360.mjs";
const require = createRequire(import.meta.url);
const { buildRegisteredEvidence } = require("../services/playerProfileEvidence");
const { buildPlayer360 } = require("../services/player360Service");
const players = require("../services/playerService").getPlayers(require("../data/players.json"));
const history = require("../data/player-match-history.json");
const archive = require("../data/historical-match-archive.json");
const matches = require("../data/matches.json");
const squads = require("../data/super-lig-squads.json");
const fixtures = [...matches, ...archive.records.map(row => row.match)];
const data = { history, squads, fixtures, registrations: [] };
const ataberk = players.find(row => row.providerId === "50216");
assert.equal(buildRegisteredEvidence(ataberk, data), null, "unregistered player is not silently rolled out");
const registration = { playerId: ataberk.id, providerId: ataberk.providerId, matchIds: ["trabzonspor-gaziantep-fk-2026-11-01"], seasonStart: "2026-07-01", priority: 3 };
data.registrations = [registration];
const evidence = buildRegisteredEvidence(ataberk, data);
assert.ok(evidence);
const metric = key => evidence.metrics.find(row => row.key === key);
assert.equal(metric("minutes").value, 90);
assert.equal(metric("saves").value, 4);
assert.equal(metric("passes").value, 30);
assert.equal(metric("passAccuracy").value, 70);
assert.equal(metric("goals").value, 0);
assert.equal(metric("shots").value, null);
assert.equal(metric("xg").value, null);
assert.equal(metric("xa").value, null);
assert.equal(evidence.pending.length, 5);
assert.equal(evidence.scope, "registered-matches");
assert.equal(evidence.matches.length, 1);
assert.equal(evidence.verifiedAt, squads.find(row => row.players.some(p => String(p.providerId) === "50216")).syncedAt);
const html = renderPlayer360({ ...buildPlayer360({ player: ataberk }), profileEvidence: evidence });
assert.ok(html.includes("sezon toplamı DEĞİLDİR"));
assert.ok(html.includes("Güncel<wbr>leniyor"));
assert.ok(html.includes("API-Football"));
assert.ok(!html.includes("Pres</span><b>0"));
const english = renderPlayer360({ ...buildPlayer360({ player: ataberk }), profileEvidence: evidence }, { locale: "en" });
assert.ok(!english.includes("player360.stat."));
assert.ok(english.includes("NOT season totals"));
assert.equal(buildRegisteredEvidence({ ...ataberk, squadStatus: "departed" }, data), null);
assert.equal(buildRegisteredEvidence({ ...ataberk, currentTeam: "Serbest oyuncu" }, data), null);
assert.equal(buildRegisteredEvidence(ataberk, { ...data, squads: [] }), null);
assert.equal(buildRegisteredEvidence(ataberk, { ...data, fixtures: [] }), null);
assert.equal(buildRegisteredEvidence(ataberk, { ...data, registrations: [{ ...registration, providerId: "wrong" }] }), null);
const gap = structuredClone(data); gap.history.rows = gap.history.rows.map(row => row.providerPlayerId === "50216" ? { ...row, passes: undefined } : row);
assert.equal(buildRegisteredEvidence(ataberk, gap).metrics.find(row => row.key === "passes").value, null);
console.log("Registered player evidence passed: actual Ataberk cached row (90min, 4 saves, 30 passes, 70%), null/zero, pending abilities, opt-in, eligibility, roster identity, fixture provenance and bilingual SSR.");
