import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { promotedNewsId } = require('../services/newsPriority.js');
const { publishableNews } = require('../services/newsFeed.js');
const { rankEnglishNews } = require('../services/englishNews.js');
const now = new Date('2026-09-21T20:00:00+03:00');
const lead = { id:'lead', slug:'lead', status:'verified', title:'Lead', body:['Text'], publishedAt:'2026-09-21T19:00:00+03:00', featuredUntil:'2026-09-22T00:00:00+03:00', editorialPriority:80, ticker:{breaking:true}, origin:'translated' };
const newer = {...lead,id:'new',slug:'new',featuredUntil:null,publishedAt:'2026-09-21T19:30:00+03:00',editorialPriority:20,origin:'english'};
assert.equal(promotedNewsId([newer,lead],now),'lead');
assert.equal(publishableNews([newer,lead],{now})[0].id,'lead');
assert.equal(rankEnglishNews([newer,lead],{now})[0].id,'lead');
assert.equal(promotedNewsId([newer,lead],new Date('2026-09-22T00:00:00+03:00')),null);
const major = {...newer,editorialPriority:90};
assert.equal(promotedNewsId([major,lead],now),'new');
assert.equal(publishableNews([major,lead],{now})[0].id,'new');
assert.equal(rankEnglishNews([major,lead],{now})[0].id,'new');
assert.equal(promotedNewsId([{...major,publishedAt:'2026-09-22T02:00:00+03:00'},lead],now),'lead');
console.log('News priority: retention, midnight expiry, higher-priority supersession and future exclusion passed.');
